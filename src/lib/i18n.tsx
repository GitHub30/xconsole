function detectBrowserLang(): Lang {
  if (typeof navigator === "undefined") return "ja";
  const lang = navigator.language;
  if (lang.startsWith("ja")) return "ja";
  if (lang.startsWith("ko")) return "ko";
  if (lang.startsWith("vi")) return "vi";
  if (lang === "zh-TW" || lang === "zh-Hant") return "zh-TW";
  if (lang.startsWith("zh")) return "zh-CN";
  if (lang.startsWith("en")) return "en";
  return "ja";
}

interface I18nContextType {
  lang: Lang;
  setLang: (l: Lang) => void;
  t: (key: string) => string;
  languages: readonly typeof LANGUAGES[number][];
  langLabel: (l: Lang) => string;
}

const I18nContext = createContext<I18nContextType>({
  lang: "ja",
  setLang: () => {},
  t: (k) => k,
  languages: LANGUAGES,
  langLabel: () => "",
});

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>("ja");

  useEffect(() => {
    const saved = localStorage.getItem("lang") as Lang | null;
    if (saved && LANGUAGES.includes(saved)) {
      setLangState(saved);
    } else {
      setLangState(detectBrowserLang());
    }
  }, []);

  const setLang = useCallback((l: Lang) => {
    setLangState(l);
    localStorage.setItem("lang", l);
  }, []);

  const t = useCallback(
    (key: string) => dictionaries[lang]?.[key] ?? dictionaries.en?.[key] ?? key,
    [lang]
  );

  return (
    <I18nContext.Provider value={{ lang, setLang, t, languages: LANGUAGES, langLabel: (l) => LANG_LABELS[l] }}>
      {children}
    </I18nContext.Provider>
  );
}

export function useI18n() {
  return useContext(I18nContext);
}
